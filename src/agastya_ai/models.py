from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator


class TestScenario(BaseModel):
    """One proposed API test scenario."""

    model_config = ConfigDict(extra="forbid")

    name: str = Field(min_length=3)
    method: Literal["GET", "POST", "PUT", "PATCH", "DELETE"]
    path: str

    path_params: dict[str, str | int] = Field(default_factory=dict)

    query_params: dict[str, str | int | float | bool] = Field(default_factory=dict)

    json_body: Any = None

    expected_status: int = Field(ge=100, le=599)
    expected_json: dict[str, Any] | None = None

    rationale: str

    @field_validator("path")
    @classmethod
    def validate_path(cls, value: str) -> str:
        if not value.startswith("/") or value.startswith("//") or "://" in value:
            raise ValueError("Use an API route path, not an absolute URL.")

        return value


class TestPlan(BaseModel):
    """A complete plan generated by AGASTYA."""

    model_config = ConfigDict(extra="forbid")

    application: str

    assumptions: list[str] = Field(default_factory=list)

    scenarios: list[TestScenario] = Field(min_length=1)
